/* Builds the textures for the /3d-test prototype. For every screen in the scene
   it writes three WebP tiers into 3d-test/tex/:
     <key>-lq.webp   48px wide: the blurred placeholder, shown at once
     <key>-sm.webp   640px wide: phones, and small or distant screens
     <key>-lg.webp   1600px wide (or the source width): large screens on desktop
   Video screens get their tiers from a frame of the video (the poster), and an
   8-second, 420px VP9 loop in 3d-test/video/ for browsers that play WebM; the
   rest (Safari) play the site's existing MP4.
   It also writes 3d-test/src/textures.js: each key's size and average colour,
   which tints the placeholder and the light the screen throws on the floor.
   Needs ImageMagick (`convert`, `identify`) and ffmpeg. Run: node tools/make-3d-textures.mjs */
import fs from 'node:fs'; import path from 'node:path'; import { execFileSync } from 'node:child_process';
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const OUT = path.join(ROOT, '3d-test/tex');
const SRC = [
  ['partner', '/assets/opt/a01fae312ee1.webp'],
  ['skymax', '/assets/opt/8cfebe82ae8c.webp'],
  ['skymax-2', '/assets/opt/cb7c6843d06b.webp'],
  ['mako', '/assets/opt/b8d3756151eb.webp'],
  ['google', '/assets/opt/e65b2bbb101d.webp'],
  ['ch13', '/assets/opt/77bb87005dfc.webp'],
  ['ni-storm', '/assets/opt/ni-ad-home-storm.mp4'],
  ['ni-street', '/assets/opt/ni-ad-street-interview.mp4'],
  ['mnh-1', '/assets/opt/4757c755e53d.webp'],
  ['mnh-2', '/assets/opt/7b39cdf80c21.webp'],
  ['mnh-3', '/assets/opt/c021d5d14394.webp'],
  ['mnh-4', '/assets/opt/bda8ea7797dc.webp'],
  ['mnh-5', '/assets/opt/4d08fb76dde2.webp'],
  ['tod', '/assets/opt/fc4eeff0b31b.webp'],
  ['simply', '/assets/opt/15b0b9d98c42.webp'],
  ['nli', '/assets/opt/e4e7d7622c15.webp'],
  ['amdocs', '/assets/opt/317245433f10.webp'],
];
fs.mkdirSync(OUT, { recursive: true });
const tmp = path.join(OUT, '.frame.png');
const lines = [];
for (const [key, src] of SRC) {
  let file = path.join(ROOT, src);
  if (src.endsWith('.mp4')) { execFileSync('ffmpeg', ['-nostdin', '-v', 'error', '-y', '-ss', '1.2', '-i', file, '-frames:v', '1', tmp]); file = tmp; }
  const [w, h] = execFileSync('identify', ['-format', '%w %h', file]).toString().trim().split(' ').map(Number);
  const tier = (suffix, width, q) => execFileSync('convert', [file, '-resize', `${Math.min(width, w)}x>`, '-strip', '-quality', String(q), '-define', 'webp:method=6', path.join(OUT, `${key}-${suffix}.webp`)]);
  tier('lq', 48, 50); tier('sm', 640, 70); tier('lg', 1600, 74);
  const hex = execFileSync('convert', [file, '-resize', '1x1!', '-format', '%[hex:p{0,0}]', 'info:']).toString().trim().slice(0, 6);
  let video = '';
  if (src.endsWith('.mp4')) {
    const webm = `/3d-test/video/${path.basename(src, '.mp4')}.webm`;
    fs.mkdirSync(path.join(ROOT, '3d-test/video'), { recursive: true });
    execFileSync('ffmpeg', ['-nostdin', '-v', 'error', '-y', '-i', path.join(ROOT, src), '-an', '-t', '8', '-vf', 'scale=-2:420,fps=25',
      '-c:v', 'libvpx-vp9', '-b:v', '0', '-crf', '46', '-row-mt', '1', '-deadline', 'good', '-cpu-used', '3', path.join(ROOT, webm)]);
    video = `, video: "${src}", webm: "${webm}"`;
  }
  lines.push(`  "${key}": { w: ${w}, h: ${h}, color: "#${hex.toLowerCase()}"${video} },`);
}
if (fs.existsSync(tmp)) fs.unlinkSync(tmp);
fs.writeFileSync(path.join(ROOT, '3d-test/src/textures.js'),
  '// Generated by tools/make-3d-textures.mjs: the size and average colour of each screen\'s image.\nexport const TEX = {\n' + lines.join('\n') + '\n};\n');
console.log(SRC.length, 'textures');
