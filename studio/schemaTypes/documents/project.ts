import {defineArrayMember, defineField, defineType} from 'sanity'

export const project = defineType({
  name: 'project',
  title: 'Project',
  type: 'document',
  groups: [
    {name: 'card', title: 'Card', default: true},
    {name: 'story', title: 'Story'},
    {name: 'media', title: 'Media'},
  ],
  fields: [
    defineField({name: 'name', type: 'string', group: 'card', validation: (rule) => rule.required()}),
    defineField({
      name: 'slug',
      type: 'slug',
      group: 'card',
      options: {source: 'name', maxLength: 64},
      validation: (rule) => rule.required(),
    }),
    defineField({name: 'client', type: 'string', group: 'card'}),
    defineField({
      name: 'category',
      type: 'string',
      group: 'card',
      options: {list: ['Brand', 'Culture', 'Technology'], layout: 'radio', direction: 'horizontal'},
      description: 'Drives the brand / culture / tech filters.',
      validation: (rule) => rule.required(),
    }),
    defineField({name: 'order', type: 'number', group: 'card', description: 'Lower comes first.'}),
    defineField({
      name: 'thumbnail',
      title: 'Card image',
      type: 'image',
      group: 'card',
      options: {hotspot: true},
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'loop',
      title: 'Card video loop',
      type: 'file',
      group: 'card',
      options: {accept: 'video/mp4'},
      description: 'Optional short mp4 that plays on the card (keep it under ~2 MB). Full films go in "Vimeo film ID".',
    }),

    defineField({
      name: 'oneliner',
      title: 'One-liner',
      type: 'string',
      group: 'story',
      validation: (rule) => rule.max(160),
    }),
    defineField({name: 'role', type: 'string', group: 'story'}),
    defineField({name: 'idea', type: 'text', rows: 3, group: 'story'}),
    defineField({name: 'outcome', type: 'text', rows: 3, group: 'story'}),
    defineField({name: 'challenge', type: 'text', rows: 3, group: 'story'}),
    defineField({name: 'system', type: 'text', rows: 3, group: 'story'}),
    defineField({name: 'contribution', type: 'text', rows: 3, group: 'story'}),
    defineField({name: 'disciplines', type: 'string', group: 'story'}),
    defineField({
      name: 'credits',
      type: 'array',
      group: 'story',
      of: [defineArrayMember({type: 'string'})],
    }),

    defineField({
      name: 'film',
      title: 'Film',
      type: 'mux.video',
      group: 'media',
      description: 'Upload the project film. It plays first when the project opens, without any player branding. Takes priority over the Vimeo ID.',
    }),
    defineField({
      name: 'vimeoId',
      title: 'Vimeo film ID',
      type: 'string',
      group: 'media',
      description: 'Fallback while a film is not uploaded above: the number in vimeo.com/123456789.',
      validation: (rule) => rule.regex(/^\d+$/, {name: 'numeric id'}),
    }),
    defineField({
      name: 'siteUrl',
      title: 'Live site',
      type: 'url',
      group: 'media',
      description: 'Adds a "visit site ↗" tag that opens the site in a new tab.',
    }),
    defineField({
      name: 'siteEmbed',
      title: 'Show the site live and clickable',
      type: 'boolean',
      group: 'media',
      initialValue: false,
      hidden: ({parent}) => !parent?.siteUrl,
      description:
        'Opens the site inside the card instead of the film. Only works if the site allows being shown inside other sites. Many (e.g. exhibition.nli.org.il) do not, and stay blank. Check the preview after turning this on.',
    }),
    defineField({name: 'hero', title: 'Hero image', type: 'image', group: 'media', options: {hotspot: true}}),
    defineField({
      name: 'gallery',
      title: 'Images & videos',
      type: 'array',
      group: 'media',
      description: 'Shown together in the mosaic under the film, in this order.',
      of: [defineArrayMember({type: 'galleryImage'}), defineArrayMember({type: 'galleryVideo'})],
      options: {layout: 'grid'},
    }),
  ],
  orderings: [{title: 'Order', name: 'orderAsc', by: [{field: 'order', direction: 'asc'}]}],
  preview: {select: {title: 'name', subtitle: 'category', media: 'thumbnail'}},
})
