/* Showcase home (index.html, built by tools/build-showcase.mjs) and the
   archive page's chrome. Static checks on the generated HTML and the
   motion script; behaviour was verified in a real browser when added. */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from './helpers/load.mjs';

const read = f => fs.readFileSync(path.join(ROOT, f), 'utf8');
const home = read('index.html');
const work = read('work.html');
const sjs = read('js/showcase.js');
const projects = JSON.parse(read('data/projects.json'));

test('home is generated from the data: ranked picks first, then flagships', () => {
  const expected = [
    ...projects.filter(p => p.homeRank).sort((a, b) => a.homeRank - b.homeRank),
    ...projects.filter(p => !p.homeRank && p.flagship),
  ].map(p => p.slug);
  const slugs = [...home.matchAll(/<article class="sc-item [^"]+" data-slug="([^"]+)"/g)].map(m => m[1]);
  assert.deepEqual(slugs, expected);
  assert.match(home, /Generated by tools\/build-showcase\.mjs/);
});

test('every project card links to a real case study and a real image with alt text', () => {
  for (const [, tag] of home.matchAll(/<article class="sc-item[\s\S]*?<\/article>/g).map(m => [null, m[0]])) {
    const hrefs = [...tag.matchAll(/href="([^"]+)"/g)].map(m => m[1]);
    assert.equal(new Set(hrefs).size, 1, 'image and caption go to the same place');
    assert.ok(fs.existsSync(path.join(ROOT, hrefs[0])), hrefs[0]);
    const src = /<img src="([^"]+)"/.exec(tag)[1];
    assert.ok(fs.existsSync(path.join(ROOT, src)), src);
    assert.match(tag, /<img [^>]*width="\d+" height="\d+" alt="[^"]+"/);
    assert.match(tag, /class="sc-link"[^>]*tabindex="-1" aria-hidden="true"/, 'one tab stop per project: the caption link');
  }
});

test('showcase carries no sales calls to action', () => {
  for (const html of [home, work]) {
    assert.doesNotMatch(html, /cal\.com|data-booking|Book a call|Send a brief|services\.html|contact\.html/);
    assert.match(html, /<nav class="sc-nav"[\s\S]*?>Work<[\s\S]*?>Archive<[\s\S]*?>Info</);
  }
});

test('home keeps the structured data brand searches rely on, without the service offer', () => {
  const graph = JSON.parse(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/.exec(home)[1])['@graph'];
  assert.ok(!graph.some(n => n['@type'] === 'ProfessionalService'));
  const list = graph.find(n => n['@type'] === 'ItemList');
  assert.equal(list.itemListElement.length, (home.match(/class="sc-item /g) || []).length);
});

test('viewer data is embedded safely and matches the cards', () => {
  const raw = /<script type="application\/json" id="scData">([\s\S]*?)<\/script>/.exec(home)[1];
  assert.doesNotMatch(raw, /<\//, 'no closing tag can break out of the data block');
  const data = JSON.parse(raw);
  assert.equal(data.length, (home.match(/class="sc-item /g) || []).length);
  for (const d of data) for (const g of [d.hero, ...d.gallery]) {
    assert.ok(fs.existsSync(path.join(ROOT, g.src)), g.src);
    assert.ok(g.w > 0 && g.h > 0 && g.alt);
  }
});

test('motion: reduced motion and missing GSAP fall back to a still page', () => {
  assert.match(sjs, /const motion=!!\(G&&window\.ScrollTrigger\)&&!reduce;/);
  assert.match(sjs, /if\(!motion\|\|!window\.SplitText\|\|!el\)return null;/);
  assert.match(sjs, /e\.metaKey\|\|e\.ctrlKey\|\|e\.shiftKey\|\|e\.altKey/, 'modified clicks still open the case study');
  assert.match(sjs, /e\.key==='Escape'/);
  assert.match(sjs, /e\.key!=='Tab'/, 'focus stays inside an open overlay');
  /* hidden states only come from script, never from the stylesheet */
  assert.doesNotMatch(read('css/showcase.css'), /clip-path:inset\(100%|opacity:0[;}]/);
});

test('GSAP scripts load before the page scripts that use them', () => {
  const order = [...home.matchAll(/<script src="([^"]+)"/g)].map(m => m[1]);
  for (const f of ['gsap.min.js', 'ScrollTrigger.min.js', 'SplitText.min.js', 'Flip.min.js']) {
    assert.ok(order.indexOf('js/vendor/gsap/' + f) > -1, f);
    assert.ok(order.indexOf('js/vendor/gsap/' + f) < order.indexOf('js/showcase.js'), f);
    assert.ok(fs.existsSync(path.join(ROOT, 'js/vendor/gsap', f)), f);
  }
});
